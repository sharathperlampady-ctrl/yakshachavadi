create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null,
  event_date date not null,
  event_time text,
  venue text not null,
  town text not null,
  artists text,
  organizer text,
  contact text,
  poster_url text,
  description text,
  status text not null default 'pending' check (status in ('pending','approved')),
  created_at timestamptz not null default now()
);
alter table public.events enable row level security;
drop policy if exists "Public can view approved events" on public.events;
create policy "Public can view approved events" on public.events for select to anon, authenticated using (status = 'approved' or auth.uid() is not null);
drop policy if exists "Public can submit events" on public.events;
create policy "Public can submit events" on public.events for insert to anon, authenticated with check (status = 'pending');
drop policy if exists "Authenticated admins can update events" on public.events;
create policy "Authenticated admins can update events" on public.events for update to authenticated using (auth.uid() is not null) with check (auth.uid() is not null);
drop policy if exists "Authenticated admins can delete events" on public.events;
create policy "Authenticated admins can delete events" on public.events for delete to authenticated using (auth.uid() is not null);
