-- ಯಕ್ಷ ಚಾವಡಿ: events + admin allowlist with Row Level Security
-- ಮೊದಲು Supabase Authentication > Users ನಲ್ಲಿ ನಿಮ್ಮ admin user ರಚಿಸಿ.
-- ನಿಮ್ಮ Admin User UID ಅನ್ನು ಕೆಳಗೆ ಸೇರಿಸಲಾಗಿದೆ.

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null,
  event_date date not null,
  event_time text,
  venue text not null,
  town text not null,
  artists text,
  organizer text,
  contact text,
  poster_url text,
  description text,
  status text not null default 'pending' check (status in ('pending','approved')),
  created_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.events enable row level security;
alter table public.admin_users enable row level security;

-- Remove earlier broad policies from the initial setup, if present.
drop policy if exists "Public can view approved events" on public.events;
drop policy if exists "Public can submit events" on public.events;
drop policy if exists "Authenticated admins can update events" on public.events;
drop policy if exists "Authenticated admins can delete events" on public.events;
drop policy if exists "Only admins can read admin list" on public.admin_users;

create policy "Public can view approved events"
on public.events for select to anon
using (status = 'approved');

create policy "Admins can view all events"
on public.events for select to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

create policy "Public can submit pending events"
on public.events for insert to anon, authenticated
with check (status = 'pending');

create policy "Admins can approve events"
on public.events for update to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

create policy "Admins can delete events"
on public.events for delete to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

create policy "Admins can read own admin record"
on public.admin_users for select to authenticated
using (user_id = auth.uid());

